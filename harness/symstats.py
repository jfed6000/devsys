#!/usr/bin/env python3
"""symstats - measure las's symbol table memory on real inputs.

Runs the measurement build (las/build/stats, compiled with -DSYMSTATS) over
the same inputs as regress.py and collects what it prints at exit:
symbols, name characters, and reference records. Reports memory as it would
be on the 6809:

  compact   12 bytes per symbol + name + terminating 0 (phase 2)
  fixed     76 bytes per symbol (before phase 2: 64-byte name box)
  refs      5 bytes per reference record

Files that stop early (FATAL) print nothing and are left out.

Usage:
    make -C las/build/stats && python3 harness/symstats.py
"""
import concurrent.futures
import os
import re
import shutil
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEVSYS = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import regress  # noqa: E402

STATS_BIN = os.path.join(DEVSYS, "las/build/stats/las")
WORK = os.path.join(HERE, "out", "symstats")
BUDGET = 25 * 1024  # low end of the 25-30K estimated free for tables (DESIGN.md §6)
LINE = re.compile(r"symstats: symbols (\d+) namechars (\d+) hostbytes \d+ bytes6809 (\d+) "
                  r"fixed6809 (\d+) refs (\d+) refbytes6809 (\d+)")


def run(job):
    rundir = os.path.join(WORK, "run", job["id"].replace("/", "__"))
    shutil.rmtree(rundir, ignore_errors=True)
    os.makedirs(rundir)
    out = os.path.join(rundir, "out.r")
    p = regress.sh([STATS_BIN] + job["args"] + [f"-o={out}"], cwd=rundir, timeout=60)
    m = LINE.search(p.stderr.decode("latin-1"))
    if not m:
        return None
    syms, chars, compact, fixed, refs, refbytes = map(int, m.groups())
    return {"id": job["id"], "symbols": syms, "avgname": chars / syms if syms else 0,
            "compact": compact, "fixed": fixed, "refs": refs, "refbytes": refbytes}


def k(n):
    return f"{n / 1024:.1f}K"


def main():
    if not os.path.exists(STATS_BIN):
        sys.exit("build it first: make -C las/build/stats")
    jobs = regress.rma_inputs() + regress.dcc_inputs()[0] + regress.lwdiff_inputs()
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as ex:
        rows = [r for r in ex.map(run, jobs) if r]

    L = ["# Symbol table memory (6809 sizes)\n",
         "Generated by `harness/symstats.py` from the `las/build/stats` measurement build. "
         "Don't edit by hand.\n",
         f"{len(rows)} of {len(jobs)} inputs ran to the end (the rest stopped early). "
         f"Budget for tables: about {k(BUDGET)}.\n"]
    for kind in ("lwdiff", "rma", "dcc"):
        rs = [r for r in rows if r["id"].startswith(kind + "/")]
        if not rs:
            continue
        L.append(f"## {kind} ({len(rs)} files)\n")
        L.append("| | Median | Largest |\n|---|---|---|")
        for key, label, fmt in (("symbols", "Symbols", str),
                                ("avgname", "Average name length", lambda v: f"{v:.1f}"),
                                ("fixed", "Table before phase 2 (76 bytes each)", k),
                                ("compact", "Table after phase 2", k),
                                ("refs", "Reference records", str),
                                ("refbytes", "Reference records, bytes", k)):
            vals = [r[key] for r in rs]
            L.append(f"| {label} | {fmt(statistics.median(vals))} | {fmt(max(vals))} |")
        over_before = sum(1 for r in rs if r["fixed"] + r["refbytes"] > BUDGET)
        over_after = sum(1 for r in rs if r["compact"] + r["refbytes"] > BUDGET)
        L.append(f"\nFiles whose symbols + references exceed {k(BUDGET)}: "
                 f"{over_before} before phase 2, {over_after} after.\n")
        L.append("Largest five after phase 2:\n")
        L.append("| File | Symbols | Table | References | Total |\n|---|---|---|---|---|")
        for r in sorted(rs, key=lambda r: -(r["compact"] + r["refbytes"]))[:5]:
            L.append(f"| `{r['id'].split('/', 1)[1]}` | {r['symbols']} | {k(r['compact'])} | "
                     f"{k(r['refbytes'])} | {k(r['compact'] + r['refbytes'])} |")
        L.append("")
    path = os.path.join(HERE, "reports", "symstats.md")
    with open(path, "w") as f:
        f.write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
